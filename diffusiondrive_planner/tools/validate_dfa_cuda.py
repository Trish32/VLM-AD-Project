SHAPES = [[(6, 8), (3, 4), (2, 2)], [(5, 7), (3, 3), (2, 3)]]  # per cam, per level
B, A, P, C, G = 2, 3, 4, 8, 2


def build_inputs(seed, dtype=torch.float32, big=False):
    """Random inputs, with border/outside sampling locations mixed in."""
    if big:
        shapes = [[(32, 88), (16, 44), (8, 22), (4, 11)] for _ in range(6)]
        b, a, p, c, g = 1, 900, 13, 256, 8
    else:
        shapes, b, a, p, c, g = SHAPES, B, A, P, C, G

    gen = torch.Generator().manual_seed(seed)
    sizes = [h * w for cam in shapes for (h, w) in cam]
    feat = torch.randn(b, sum(sizes), c, generator=gen, dtype=dtype)
    spatial_shape = torch.tensor(shapes, dtype=torch.int64)
    starts = (torch.tensor(sizes, dtype=torch.int64).cumsum(0)
              - torch.tensor(sizes, dtype=torch.int64))
    scale_start_index = starts.reshape(len(shapes), -1)

    loc = torch.rand(b, a, p, len(shapes), 2, generator=gen, dtype=dtype)
    if not big:
        # Exercise the kernel's strict early-return.
        loc[0, 0, 0, 0] = torch.tensor([0.0, 0.5], dtype=dtype)
        loc[0, 0, 1, 0] = torch.tensor([1.0, 0.5], dtype=dtype)
        loc[0, 1, 0, 0] = torch.tensor([-0.3, 0.5], dtype=dtype)
        loc[0, 1, 1, 0] = torch.tensor([0.5, 1.7], dtype=dtype)

    weights = torch.randn(b, a, p, len(shapes), len(shapes[0]), g,
                          generator=gen, dtype=dtype)
    return [x.cuda() for x in
            (feat, spatial_shape, scale_start_index, loc, weights)]


