def diagnose(name, got, want, err, denom):
    """Explain any large RELATIVE error.

    A big relative error with a tiny absolute error is the expected signature of
    float32 accumulation-order differences: the CUDA kernel sums via atomicAdd in
    nondeterministic order across cam x scale x pts, while the torch version sums in a
    fixed loop order. That shows up as a large ratio only where the true value is near
    zero, which is harmless.

    The failure mode it must be distinguished from is a genuine structural mismatch,
    which would produce large relative error on LARGE values too. So report the relative
    error restricted to elements that actually carry magnitude.
    """
    rel = err / denom
    i = int(rel.argmax())
    flat_want, flat_err = want.flatten(), err.flatten()

    scale = float(want.abs().median())
    big = want.abs() > max(scale, 1e-3)          # elements that carry real magnitude
    rel_big = float((rel[big]).max()) if bool(big.any()) else float("nan")
    frac_bad = float((rel > 1e-2).float().mean())

    print(f"{'':<28}worst-rel elem: |want|={abs(float(flat_want[i])):.3e} "
          f"err={float(flat_err[i]):.3e}")
    print(f"{'':<28}median |want|={scale:.3e} | max rel on |want|>median: {rel_big:.3e} "
          f"| frac rel>1%: {frac_bad:.2%}")
    if rel_big > 1e-3:
        print(f"{'':<28}^^ WARNING: large relative error on LARGE values — "
              f"this is NOT just accumulation order.")


# ------------------------------------------------------------------------ main

def main():
    ext = build_extension()

    print()
    print("=" * 66)
    print(f"{'case':<28}{'max abs diff':>16}{'max rel diff':>14}  verdict")
    print("=" * 66)

    worst = 0.0
    failures = 0
    cases = [("tiny seed=0", 0, False), ("tiny seed=1", 1, False),
             ("tiny seed=2", 2, False), ("realistic 900x13x256", 0, True)]

    for name, seed, big in cases:
        args = build_inputs(seed, big=big)
        feat, spatial_shape, scale_start_index, loc, weights = args

        want = ext.deformable_aggregation_forward(
            feat.contiguous().float(),
            spatial_shape.contiguous().int(),
            scale_start_index.contiguous().int(),
            loc.contiguous().float(),
            weights.contiguous().float(),
        )
        got = deformable_aggregation_torch(*args)

        denom = want.abs().clamp(min=1e-6)
        err = (got - want).abs()
        abs_d = float(err.max())
        rel_d = float((err / denom).max())
        ok = abs_d < 1e-3
        failures += (not ok)
        worst = max(worst, abs_d)
        print(f"{name:<28}{abs_d:>16.3e}{rel_d:>14.3e}  {'PASS' if ok else 'FAIL'}")
        diagnose(name, got, want, err, denom)

    print("=" * 66)
    if failures:
        print(f"\n{failures} case(s) FAILED — dfa_torch.py does NOT match the kernel.")
        print("Do not trust any metric produced with the pure-PyTorch fallback.")
    else:
        print(f"\nAll cases PASS (worst abs diff {worst:.3e}).")
        print("dfa_torch.py is confirmed equivalent to the CUDA kernel.")
    return failures


def _in_notebook() -> bool:
    try:
        get_ipython()  # noqa: F821  — only defined inside IPython/Jupyter
        return True
    except NameError:
        return False


# Works both as `python validate_dfa_cuda.py` and as a pasted notebook cell.
# SystemExit inside a Jupyter cell renders as an ugly traceback, so it is only
# raised when actually running as a script.
_rc = main()
if _rc and not _in_notebook():
    raise SystemExit(_rc)
